#!/usr/bin/env node
// Trains the small networks shipped with the "Diffusion models from scratch" series and writes them to
// assets/js/diffusion/dm-weights.js, so each page can sample straight away (readers can still retrain live).
//
//   node bin/dm-pretrain.js            # every network
//   node bin/dm-pretrain.js swissroll  # only the ones whose name starts with "swissroll"
//
// Seeded: the same command always writes the same weights. Takes a few minutes per network.
"use strict";

const fs = require("fs");
const path = require("path");
const DM = require("../assets/js/diffusion/dm-core.js");

const OUT = path.join(__dirname, "../assets/js/diffusion/dm-weights.js");

// name → how it was trained. T = 200 steps with the linear schedule of Ho et al. stretched to 200 steps.
const NETS = {
  "swissroll-eps": { dataset: "swissroll", schedule: "linear", T: 200, target: "eps", steps: 30000, seed: 1 },
  "swissroll-x0": { dataset: "swissroll", schedule: "linear", T: 200, target: "x0", steps: 30000, seed: 1 },
  "swissroll-vlb": { dataset: "swissroll", schedule: "linear", T: 200, target: "eps", weighting: "vlb", steps: 30000, seed: 1 },
  // Improved DDPM's learned variance (part 8): a third output v, trained with the hybrid loss
  "swissroll-learned": { dataset: "swissroll", schedule: "linear", T: 200, target: "eps", out: 3, steps: 30000, seed: 1 },
  // classifier-free guidance (part 9): conditioned on the class (or "no class", dropped with probability 0.2)
  "classes-cfg": { dataset: "classes", schedule: "linear", T: 200, target: "eps", K: 4, pUncond: 0.2, steps: 30000, seed: 1 },
  // a noise-conditional score network (part 5): 10 noise levels from 0.03 to 4, x̃ = x + σ·ε, trained to predict ε
  "twomodes-ncsn": { dataset: "twomodes", schedule: "ve", sigmaMax: 4, sigmaMin: 0.03, T: 10, target: "eps", steps: 30000, seed: 1 },
};

function train(name, spec) {
  const data = DM.DATASETS[spec.dataset];
  const sch = spec.schedule === "ve" ? DM.veSchedule(spec.sigmaMax, spec.sigmaMin, spec.T) : DM.schedule(spec.schedule, spec.T);
  const net = DM.createNet(spec.seed, [2 + DM.EMBED + (spec.K || 0), 48, 48, 48, spec.out || 2]);
  net.K = spec.K || 0;
  const tr = DM.trainer(net, data, sch, {
    steps: spec.steps,
    target: spec.target,
    weighting: spec.weighting,
    pUncond: spec.pUncond,
    batch: 256,
    seed: spec.seed + 100,
  });
  const start = Date.now();
  let avg = 0;
  for (let i = 1; i <= spec.steps; i++) {
    avg += tr.step();
    if (i % 2000 === 0) {
      console.log(`${name}: step ${i}, loss ${(avg / 2000).toFixed(4)}, ${((Date.now() - start) / 1000).toFixed(0)} s`);
      avg = 0;
    }
  }
  if (sch.kind === "ve" || net.K) return { ...spec, w: DM.encodeWeights(net.w) };
  const frames = DM.ddpmSample(DM.netModel(net, sch), sch, DM.gaussian(1000, 2));
  const sw = DM.sliced(frames[0], DM.sample(data, 1000, 9).xs);
  console.log(`${name}: sliced Wasserstein distance of 1000 samples to the data: ${sw.toFixed(4)}`);
  return { ...spec, w: DM.encodeWeights(net.w), sw: Number(sw.toFixed(4)) };
}

// keep networks already in the file unless they are retrained now
let existing = {};
if (fs.existsSync(OUT)) {
  const sandbox = { window: { DM: {} } };
  new Function("window", fs.readFileSync(OUT, "utf8"))(sandbox.window);
  existing = sandbox.window.DM.WEIGHTS || {};
}

const only = process.argv[2];
const weights = { ...existing };
Object.entries(NETS).forEach(([name, spec]) => {
  if (only && !name.startsWith(only)) return;
  weights[name] = train(name, spec);
});

const body = Object.entries(weights)
  .map(([name, spec]) => `    ${JSON.stringify(name)}: ${JSON.stringify(spec)},`)
  .join("\n");
fs.writeFileSync(
  OUT,
  `// Generated by bin/dm-pretrain.js: do not edit. Trained networks for the diffusion series, as base64 Float32
// weights for DM.loadNet. Each entry records how it was trained, and sw is the sliced Wasserstein distance of
// 1000 samples to the data (smaller is closer).
(function (root) {
  root.DM = root.DM || {};
  root.DM.WEIGHTS = {
${body}
  };
})(typeof window !== "undefined" ? window : globalThis);
`
);
console.log(`wrote ${path.relative(process.cwd(), OUT)}`);
